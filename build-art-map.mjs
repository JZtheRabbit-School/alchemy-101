// Regenerate the stable name-to-sprite map. Item order never determines atlas coordinates.
import {readFileSync,writeFileSync} from 'node:fs';
const read=p=>JSON.parse(readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const map={};
function add(names,path,width,height,cols,rows,kind){names.forEach((name,i)=>{
 const cw=width/cols,ch=height/rows,col=i%cols,row=Math.floor(i/cols);
 let x=(col+.04)*cw,y=(row+.04)*ch,w=.92*cw,h=.92*ch;
 if(kind==='revised'){x=(col+.025)*cw;y=(row+.025)*ch;w=.95*cw;h=.95*ch;if(row===5){y=(row-.06)*ch;h=.96*ch;}if(row===6){y=(row-.06)*ch;h=1.04*ch;}}
 if(kind==='vine'){x=col*cw+8;y=50;w=cw-16;h=height-100;}
 if(kind==='holy'){x=(col+.015)*cw;y=(row+.015)*ch;w=.97*cw;h=.97*ch;if(i===4)w=cw-34;}
 map[name]={path,width,height,box:[x,y,w,h]};
});}
add(read('assets/revisions-2026-11-16/all-labels.json').slice(0,63),'assets/items-illustrated.png',1254,1254,8,8);
add(read('assets/revisions-2026-11-16/labels.json'),'assets/revisions-2026-11-16/items-revised.png',948,1659,4,7,'revised');
add(['Vine','Grape','Pulp','Wine','Jesus'],'assets/vine-chain-2026-11-16/items-new.png',2172,724,5,1,'vine');
add(['Cross','Holy Water','A Glass of Holy Water','A Pot of Holy Water','Raisins','Raisins Bread'],'assets/holy-chain-2026-11-16/items-new.png',1536,1024,3,2,'holy');
writeFileSync('art-map.js','// Generated by build-art-map.mjs\nexport const sprites='+JSON.stringify(map,null,2)+';\n');
